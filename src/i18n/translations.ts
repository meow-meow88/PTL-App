const LANG_KEY = 'ptl_language';

export function getStoredLanguage(): Language {
  const stored = safeGetLocalStorage(LANG_KEY);
  if (stored === 'th' || stored === 'en') {
    return stored;
  }
  return 'en'; // Default English as required
}

export function setStoredLanguage(lang: Language): void {
  safeSetLocalStorage(LANG_KEY, lang);
}

export function useLanguage() {
  const [lang, setLangState] = useState<Language>(getStoredLanguage);

  useEffect(() => {
    const handleLanguageUpdate = () => {
      setLangState(getStoredLanguage());
    };
    window.addEventListener('storage', handleLanguageUpdate);
    window.addEventListener('ptl_language_changed', handleLanguageUpdate);
    return () => {
      window.removeEventListener('storage', handleLanguageUpdate);
      window.removeEventListener('ptl_language_changed', handleLanguageUpdate);
    };
  }, []);

  const changeLanguage = (newLang: Language) => {
    setStoredLanguage(newLang);
    setLangState(newLang);
    window.dispatchEvent(new Event('ptl_language_changed'));
  };

  const t = translations[lang];

  return {
    lang,
    setLanguage: changeLanguage,
    t,
  };
}
